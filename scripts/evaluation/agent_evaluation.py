"""
Script that reads saved results of API calling generated by LLMs and evaluates them by comparing the generated data with ground-truth API calls.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any
import pandas as pd
import yaml
from evaluation.api_calling_metrics import compute_instance_metrics

PROJECT_ROOT = Path(__file__).resolve().parents[2]
SRC_DIR = PROJECT_ROOT / "src"
sys.path.insert(0, str(SRC_DIR))
EVAL_CONFIG_PATH = PROJECT_ROOT / "config" / "evaluation.yaml"
RESULTS_DIR = PROJECT_ROOT / "results"


def _safe_name(name: str) -> str:
	return name.replace("/", "__").replace(" ", "_")


def _resolve_from_project(path_str: str) -> Path:
	path = Path(path_str)
	if path.is_absolute():
		return path
	return PROJECT_ROOT / path


def _load_config(path: Path) -> dict[str, Any]:
	if not path.exists():
		raise FileNotFoundError(f"Could not find config file at: {path}")
	with path.open("r", encoding="utf-8") as f:
		cfg = yaml.safe_load(f)

	required = [
		"dataset_path",
		"generation_method",
		"llm_used_for_data_generation",
		"llm_used_in_agent",
	]
	missing = [k for k in required if k not in cfg]
	if missing:
		raise ValueError(f"Missing required config fields in {path}: {missing}")
	return cfg


def _load_results_jsonl(path: Path) -> list[dict[str, Any]]:
	if not path.exists():
		raise FileNotFoundError(f"Results file not found: {path}")
	rows: list[dict[str, Any]] = []
	with path.open("r", encoding="utf-8") as f:
		for line_num, line in enumerate(f, start=1):
			line = line.strip()
			if not line:
				continue
			try:
				rows.append(json.loads(line))
			except json.JSONDecodeError as exc:
				raise ValueError(f"Invalid JSONL at line {line_num} in {path}: {exc}") from exc
	return rows


def _build_ground_truth_queue(test_df: pd.DataFrame) -> dict[str, list[str]]:
	queue: dict[str, list[str]] = defaultdict(list)
	for _, row in test_df.iterrows():
		utterance = str(row.get("utterance", ""))
		queue[utterance].append(row.get("api_calls", ""))
	return queue


def evaluate_agent_results(
	test_df: pd.DataFrame,
	result_rows: list[dict[str, Any]],
) -> tuple[pd.DataFrame, dict[str, Any]]:
	"""Compute per-instance and average ESR/ASP/EM over result rows."""
	gt_queue = _build_ground_truth_queue(test_df)
	fallback_gt = test_df["api_calls"].tolist() if "api_calls" in test_df.columns else []

	per_instance: list[dict[str, Any]] = []
	missing_ground_truth = 0

	for idx, row in enumerate(result_rows):
		utterance = str(row.get("utterance", ""))
		gt_calls = None

		if utterance in gt_queue and gt_queue[utterance]:
			gt_calls = gt_queue[utterance].pop(0)
		elif idx < len(fallback_gt):
			gt_calls = fallback_gt[idx]
			missing_ground_truth += 1
		else:
			gt_calls = "[]"
			missing_ground_truth += 1

		metrics = compute_instance_metrics(
			predicted_calls=row.get("predicted_calls"),
			execution_results=row.get("execution_results"),
			ground_truth_calls=gt_calls,
		)

		per_instance.append(
			{
				"index": idx,
				"utterance": utterance,
				"esr": metrics["esr"],
				"asp": metrics["asp"],
				"sem": metrics["sem"],
				"predicted_call_count": len(row.get("predicted_calls") or []),
				"execution_total": row.get("execution_total", 0),
				"execution_successes": row.get("execution_successes", 0),
			}
		)

	per_instance_df = pd.DataFrame(per_instance)
	if per_instance_df.empty:
		summary = {
			"n_instances": 0,
			"avg_esr": 0.0,
			"avg_asp": 0.0,
			"avg_sem": 0.0,
		}
	else:
		summary = {
			"n_instances": int(len(per_instance_df)),
			"avg_esr": float(per_instance_df["esr"].mean()),
			"avg_asp": float(per_instance_df["asp"].mean()),
			"avg_sem": float(per_instance_df["sem"].mean()),
		}

	return per_instance_df, summary


def parse_args() -> argparse.Namespace:
	parser = argparse.ArgumentParser(description="Evaluate agent API-calling results.")
	parser.add_argument("--config", type=Path, default=EVAL_CONFIG_PATH)
	parser.add_argument("--generation-method", default=None)
	parser.add_argument("--agent-model", default=None)
	parser.add_argument("--results-file", type=Path, default=None)
	parser.add_argument("--output-dir", type=Path, default=None)
	return parser.parse_args()


def main(
	cfg: dict[str, Any] | None = None,
	generation_method: str | None = None,
	agent_model: str | None = None,
	results_file: Path | None = None,
	output_dir: Path | None = None,
) -> dict[str, Any]:
	"""
	Run agent evaluation.
	
	Args:
		cfg: Configuration dict. If None, loads from EVAL_CONFIG_PATH
		generation_method: Override generation method
		agent_model: Override agent model name
		results_file: Override results file path
		output_dir: Override output directory
		
	Returns:
		Summary dict with evaluation results
	"""
	if cfg is None:
		args = parse_args()
		cfg = _load_config(args.config)
		generation_method = generation_method or args.generation_method or cfg["generation_method"]
		agent_model = agent_model or args.agent_model or cfg["llm_used_in_agent"]
		results_file = results_file or args.results_file
		output_dir = output_dir or args.output_dir
	else:
		generation_method = generation_method or cfg.get("generation_method")
		agent_model = agent_model or cfg.get("llm_used_in_agent")
	
	dataset_root = _resolve_from_project(cfg["dataset_path"])

	test_path = dataset_root / "test" / f"{generation_method}.csv"
	if not test_path.exists():
		raise FileNotFoundError(f"Test dataset file not found: {test_path}")

	if results_file is None:
		results_file = RESULTS_DIR / "agent" / generation_method / f"{_safe_name(agent_model)}.jsonl"

	if output_dir is None:
		output_dir = RESULTS_DIR / "agent" / generation_method
	output_dir.mkdir(parents=True, exist_ok=True)

	test_df = pd.read_csv(test_path, sep=None, engine="python")
	result_rows = _load_results_jsonl(results_file)

	per_instance_df, summary = evaluate_agent_results(test_df, result_rows)

	per_instance_path = output_dir / f"{_safe_name(agent_model)}__per_instance_metrics.csv"
	summary_path = output_dir / f"{_safe_name(agent_model)}__evaluation_summary.json"

	per_instance_df.to_csv(per_instance_path, index=False)
	
	full_summary = {
		"generation_method": generation_method,
		"data_model": cfg.get("llm_used_for_data_generation"),
		"agent_model": agent_model,
		"test_file": str(test_path.relative_to(PROJECT_ROOT)),
		"results_file": str(results_file.relative_to(PROJECT_ROOT)),
		**summary,
	}
	
	with summary_path.open("w", encoding="utf-8") as f:
		json.dump(full_summary, f, ensure_ascii=False, indent=2)

	print("Agent evaluation completed.")
	print(f"Instances: {summary['n_instances']}")
	print(f"Average ESR: {summary['avg_esr']:.4f}")
	print(f"Average ASP: {summary['avg_asp']:.4f}")
	print(f"Average SEM: {summary['avg_sem']:.4f}")
	print(f"Per-instance file: {per_instance_path}")
	print(f"Summary file: {summary_path}")
	
	return full_summary


if __name__ == "__main__":
	main()