"""
Overview:
    Stylometric analysis by country.
    Used to analyse whether the L1-APG method can generate utterances that have distinct stylometric features based on the country of the persona. 
"""

import sys
import yaml
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path
from rich.console import Console
from sklearn.preprocessing import StandardScaler
from evaluation.stylometric_metrics import extract_features_batch, load_spacy_model
from scipy.spatial.distance import cosine
from scipy.stats import mannwhitneyu

console = Console()
RNG_SEED = 42
N_PERMUTATIONS = 10000

def load_config(path: Path) -> dict:
    """Loads configuration to be used in the generation method."""
    if not path.exists():
        console.log(f"[red]Error:[/] Could not find configuration file at {path}")
        sys.exit(1)
    with path.open("r") as f:
        cfg = yaml.safe_load(f)
    required = ["dataset_path", "llm_used_for_data_generation", "generation_method"]
    for key in required:
        if key not in cfg:
            console.log(f"[red]Error:[/] Missing required field '{key}' in {path}")
            sys.exit(1)
    return cfg

def main(cfg = None, save_picture = False):
    if cfg is None:
        cfg = load_config(Path(__file__).parent.parent.parent / "config" / "evaluation.yaml")

    # reading config file
    llm_model = cfg["llm_used_for_data_generation"]
    dataset_path = Path(cfg["dataset_path"]) / "full"
    gen_strategy = cfg["generation_method"]
    llm_name = llm_model if not '/' in llm_model else llm_model.split('/')[1]

    if gen_strategy != "l1-apg":
        console.log(f"[red]Error:[/] Stylometric analysis is only applicable for the 'l1-apg' generation strategy. Current strategy: '{gen_strategy}'")
        return {"d_within": ' - ', "d_between": ' - ', "p_value_cc": ' - '}
    console.log(f"Evaluating cross-country stylometric metrics for '{llm_model}'")      

    # reading dataset
    utterances_filepath = Path(dataset_path) / gen_strategy / f"{llm_name}.csv"
    train_df = pd.read_csv(utterances_filepath, sep=None, engine="python")
    console.log(f"Loaded dataset with {len(train_df)} utterances generated by {llm_name} using {gen_strategy} strategy.")

    # organising texts and labels per country and persona
    utterances = []
    labels = []  

    for country in train_df["country"].unique():
        country_df = train_df[train_df["country"] == country]

        for persona_index in country_df["persona_number"].unique():
            persona_texts = country_df[country_df["persona_number"] == persona_index]["utterance"].tolist()
            persona_texts_concatenated = " ".join(persona_texts)
            utterances.append(persona_texts_concatenated)
            labels.append(country)

    # compute stylometric distance matrix and perform statistical test
    ## computing vectors
    nlp = load_spacy_model(model_name="en_core_web_sm", require_gpu=True)
    vectors = extract_features_batch(utterances, nlp_model=nlp)
    countries = sorted(set(labels))

    ## standardising features
    scaler = StandardScaler()
    vectors = scaler.fit_transform(vectors)

    ## computing distances and performing statistical test
    d_within_countries = []
    d_between_countries = []
    country_pairs = {(c1, c2): [] for c1 in countries for c2 in countries}
    pair_i = []
    pair_j = []
    pair_d = []

    for i in range(len(vectors)):
        for j in range(i + 1, len(vectors)):
            d = cosine(vectors[i], vectors[j])
            c1, c2 = labels[i], labels[j]
            country_pairs[(c1, c2)].append(d)
            country_pairs[(c2, c1)].append(d)
            pair_i.append(i)
            pair_j.append(j)
            pair_d.append(d)
            
            if c1 == c2:
                d_within_countries.append(d)
            else:
                d_between_countries.append(d)

    d_within = np.array(d_within_countries, dtype=np.float64).mean()
    d_between = np.array(d_between_countries, dtype=np.float64).mean()
    delta_observed = d_between - d_within

    # Mann-Whitney U test (one-sided): within-country distances are smaller.
    _, p_value_mw = mannwhitneyu(d_within_countries, d_between_countries, alternative="less")

    # Label-permutation test: preserves pairwise dependence structure while
    # testing whether between-country separation is larger than chance.
    rng = np.random.default_rng(RNG_SEED)
    labels_array = np.array(labels)
    pair_i = np.array(pair_i, dtype=np.int32)
    pair_j = np.array(pair_j, dtype=np.int32)
    pair_d = np.array(pair_d, dtype=np.float64)

    perm_deltas = np.empty(N_PERMUTATIONS, dtype=np.float64)
    for b in range(N_PERMUTATIONS):
        permuted_labels = labels_array[rng.permutation(len(labels_array))]
        within_mask = permuted_labels[pair_i] == permuted_labels[pair_j]
        between_mask = ~within_mask
        perm_within = pair_d[within_mask].mean()
        perm_between = pair_d[between_mask].mean()
        perm_deltas[b] = perm_between - perm_within

    p_value_perm = (1.0 + np.sum(perm_deltas >= delta_observed)) / (N_PERMUTATIONS + 1.0)

    # results
    results = {
        "d_within": round(d_within, 4),
        "d_between": round(d_between, 4),
        "delta_cc": round(delta_observed, 4),
        "p_value_mw": p_value_mw,
        "p_value_cc": p_value_perm,
    }
    console.log(
        f"d_within: {results['d_within']}, d_between: {results['d_between']}, "
        f"delta_cc: {results['delta_cc']}, p_value_mw: {results['p_value_mw']:.6g}, "
        f"p_value_cc: {results['p_value_cc']:.6g}"
    )
    
    # saving results and picture of the distance matrix
    if save_picture: 
        matrix = pd.DataFrame(index=countries, columns=countries, dtype=float)
        for c1 in countries:
            for c2 in countries:
                values = country_pairs[(c1, c2)]
                matrix.loc[c1, c2] = np.mean(values) if values else 0.0

        output_dir = dataset_path / "l1-apg"
        output_dir.mkdir(parents=True, exist_ok=True)
        matrix.to_excel(output_dir / f"{llm_name}_country_distance_matrix.xlsx")

        plt.figure(figsize=(14, 10))
        plt.imshow(matrix.values)
        plt.colorbar(label="Cosine distance")
        plt.xticks(range(len(matrix.columns)), matrix.columns, rotation=60, ha="right", fontsize=12)
        plt.yticks(range(len(matrix.index)), matrix.index, fontsize=12)
        plt.title("Country Distance Matrix", fontsize=14)
        plt.tight_layout()
        plt.savefig(output_dir / f"{llm_name}_country_distance_matrix.png", dpi=300)
        plt.close()

    return results

if __name__ == "__main__":
    main()